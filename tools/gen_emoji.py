#!/usr/bin/env python3
"""Generates the emoji tables from Unicode data files.

  tools/gen_emoji.py <emoji-test.txt> <emoji-data.txt>

writes modules/emoji/emoji_catalog.inc (picker list: groups, emoji, names, skin tone support; module side)
and src/app/emoji_props.inc (code point ranges used to find emoji in text; app side).
"""
import os, re, sys

MAX_VERSION = 15.0  # what current Windows 11 and Android draw
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
test, data = sys.argv[1], sys.argv[2]
TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}

groups, fq = [], set()
for line in open(test, encoding='utf-8'):
    if line.startswith('# group:'):
        g = line.split(':', 1)[1].strip()
        groups.append([g, []])
        continue
    m = re.match(r'^([0-9A-F ]+);\s*fully-qualified\s*#\s*\S+\s+E(\d+\.\d+)\s+(.*)$', line.strip())
    if not m:
        continue
    cps = [int(x, 16) for x in m.group(1).split()]
    fq.add(tuple(cps))
    if float(m.group(2)) > MAX_VERSION or groups[-1][0] == 'Component':
        continue
    groups[-1][1].append((cps, m.group(3)))

def toned(cps, tone):
    """the skin tone variant: modifier after the first code point (dropping its FE0F)"""
    rest = cps[1:]
    if rest and rest[0] == 0xFE0F:
        rest = rest[1:]
    return tuple([cps[0], tone] + rest)

def c_str(cps):
    return ''.join('\\x%02x' % b for b in ''.join(map(chr, cps)).encode('utf-8'))

out = ['// Generated by tools/gen_emoji.py from Unicode emoji-test.txt (emoji up to version %.1f). Do not edit.' % MAX_VERSION,
       '// Each entry: UTF-8 emoji, name; flag 1 = has skin tones (modifier goes after the first code point).']
count = 0
for g, items in groups:
    items = [(c, n) for c, n in items if not any(x in TONES for x in c)]
    if not items:
        continue
    out.append('LSE_GROUP("%s")' % g)
    for cps, name in items:
        tone = all(toned(cps, t) in fq for t in TONES)
        out.append('LSE_EMOJI("%s", "%s", %d)' % (c_str(cps), name.replace('"', '\\"'), 1 if tone else 0))
        count += 1
open(os.path.join(root, 'modules/emoji/emoji_catalog.inc'), 'w').write('\n'.join(out) + '\n')

props = {'Emoji_Presentation': [], 'Extended_Pictographic': [], 'Emoji': []}
for line in open(data, encoding='utf-8'):
    line = line.split('#')[0].strip()
    if not line:
        continue
    r, p = [x.strip() for x in line.split(';')]
    if p not in props:
        continue
    a, _, b = r.partition('..')
    props[p].append((int(a, 16), int(b or a, 16)))

def merged(rs):
    rs = sorted(rs)
    o = []
    for a, b in rs:
        if o and a <= o[-1][1] + 1:
            o[-1] = (o[-1][0], max(o[-1][1], b))
        else:
            o.append((a, b))
    return o

o = ['// Generated by tools/gen_emoji.py from Unicode emoji-data.txt. Do not edit.']
for p, name in (('Emoji_Presentation', 'kEmojiPresentation'), ('Extended_Pictographic', 'kExtPict'), ('Emoji', 'kEmoji')):
    rs = merged(props[p])
    o.append('static const uint32_t %s[][2] = {' % name)
    for i in range(0, len(rs), 6):
        o.append('    ' + ' '.join('{0x%X, 0x%X},' % r for r in rs[i:i + 6]))
    o.append('};')
open(os.path.join(root, 'src/app/emoji_props.inc'), 'w').write('\n'.join(o) + '\n')
print('%d emoji in %d groups' % (count, len(groups)))
